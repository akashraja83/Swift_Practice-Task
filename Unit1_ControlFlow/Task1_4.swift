// Task 1.4 - Use a switch statement to print the day name for numbers 1–7.
import Foundation

let dayNumber = 4

switch dayNumber {
case 1:
    print("Monday")
case 2:
    print("Tuesday")
case 3:
    print("Wednesday")
case 4:
    print("Thursday")
case 5:
    print("Friday")
case 6:
    print("Saturday")
case 7:
    print("Sunday")
default:
    print("Invalid")
}
